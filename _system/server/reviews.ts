import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import type { ReviewItem, ReviewRound } from '../shared/types.ts';
import { HttpError, assertNoSymlinks, projectId, registeredRoot } from './security.ts';
import { appendTarget } from './projects.ts';
import { atomicWrite, readJson, withLock, writeJson } from './storage.ts';

function tex(value: string): string { const replacements: Record<string,string> = { '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '#': '\\#', '%': '\\%', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}' }; return value.replace(/[\\{}$&#%_^~]/g, char => replacements[char]).replace(/\r?\n/g, '\n\\par\n'); }
function responses(items: ReviewItem[]): string {
  return '% Generated by the review editor. Edit the structured review fields in the workbench.\n' + (items.length ? items.map((item,index) => `\\subsection*{${tex(item.reviewer || `Reviewer ${index + 1}`)} --- ${tex(item.id)}}\n\\textbf{Comment.}\\par\n${tex(item.comment || '(Comment not entered.)')}\n\\par\\medskip\n\\textbf{Response.}\\par\n${tex(item.response || '(Response not entered.)')}\n\\par\\medskip\n\\textbf{Changes.} ${tex(item.location || '(Location not entered.)')}\n`).join('\n') : '\\section*{Responses}\nNo review comments have been entered yet.\n');
}
export async function listReviews(workspaceRoot: string, id: string): Promise<ReviewRound[]> {
  const root = await registeredRoot(workspaceRoot, id); const base = await assertNoSymlinks(root, 'reviews', true); await fs.mkdir(base, { recursive: true }); await assertNoSymlinks(root,'reviews');
  const rounds: ReviewRound[] = [];
  for (const entry of await fs.readdir(base, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.isSymbolicLink()) continue;
    try { await assertNoSymlinks(root, `reviews/${entry.name}/round.json`); rounds.push(await readJson<ReviewRound>(path.join(base, entry.name, 'round.json'))); }
    catch (error) { if ((error as HttpError).statusCode === 404 || error instanceof SyntaxError) continue; throw error; }
  }
  return rounds.sort((a,b) => a.createdAt.localeCompare(b.createdAt));
}
export async function createReview(workspaceRoot: string, id: string, labelValue: unknown): Promise<ReviewRound> {
  if (labelValue !== undefined && (typeof labelValue !== 'string' || labelValue.length > 200)) throw new HttpError(400, '审稿轮次名称无效。');
  return withLock(`review:${id}`, async () => {
    const root = await registeredRoot(workspaceRoot, id); const existing = await listReviews(workspaceRoot, id);
    let number = existing.length + 1; let roundId = `round-${String(number).padStart(2,'0')}`;
    while (await fs.stat(path.join(root, 'reviews', roundId)).then(() => true).catch(() => false)) roundId = `round-${String(++number).padStart(2,'0')}`;
    const roundRoot = path.join(root, 'reviews', roundId); await fs.mkdir(roundRoot);
    try {
    await fs.mkdir(path.join(roundRoot, 'original'), { recursive: true }); await fs.mkdir(path.join(roundRoot, 'response'), { recursive: true });
    await fs.writeFile(path.join(roundRoot, 'original', 'original.md'), '# 审稿原文\n\n请将收到的审稿意见原文保存在这里。\n');
    await fs.writeFile(path.join(roundRoot, 'changes.md'), '# 修改对照\n\n记录意见编号、修改内容、对应文件与位置。\n');
    const templatePath = path.join(workspaceRoot, 'shared', 'templates', 'response', 'main.tex');
    let main = await fs.readFile(templatePath, 'utf8').catch(() => '\\documentclass[11pt]{article}\n\\usepackage[margin=1in]{geometry}\n\\usepackage{hyperref}\n\\begin{document}\n\\section*{Response to Reviewers}\n\\input{responses}\n\\end{document}\n');
    if (!/\\input\s*\{responses(?:\.tex)?\}/.test(main)) main = main.replace('\\end{document}', '\\input{responses}\n\\end{document}');
    await fs.writeFile(path.join(roundRoot, 'response', 'main.tex'), main);
    await fs.writeFile(path.join(roundRoot, 'response', 'responses.tex'), responses([]));
    const result: ReviewRound = { id: roundId, label: typeof labelValue === 'string' && labelValue.trim() ? labelValue.trim() : `第 ${number} 轮审稿`, createdAt: new Date().toISOString(), targetId: `review-${roundId}`, items: [] };
    await writeJson(path.join(roundRoot, 'round.json'), result);
    await appendTarget(workspaceRoot, id, { id: result.targetId, label: `${result.label}回复`, main: `reviews/${roundId}/response/main.tex` });
    return result;
    } catch (error) { await fs.rm(roundRoot,{recursive:true,force:true}); throw error; }
  });
}
export async function updateReview(workspaceRoot: string, id: string, roundId: string, itemsValue: unknown): Promise<ReviewRound> {
  projectId(roundId);
  if (!Array.isArray(itemsValue) || itemsValue.length > 500) throw new HttpError(400, '每轮最多保存 500 条意见。');
  const ids = new Set<string>();
  const items: ReviewItem[] = itemsValue.map((item,index) => {
    if (!item || typeof item !== 'object') throw new HttpError(400, '审稿意见无效。');
    const field = (key: string, fallback = '') => { const value = item[key] ?? fallback; if (typeof value !== 'string' || value.length > 50000) throw new HttpError(400, '审稿字段无效或过长。'); return value; };
    const itemId = field('id', `item-${index + 1}-${randomUUID().slice(0,8)}`); if (!itemId || ids.has(itemId)) throw new HttpError(400, '意见编号不能为空或重复。'); ids.add(itemId);
    if (!['open','addressed'].includes(item.status ?? 'open')) throw new HttpError(400, '意见状态无效。');
    return { id: itemId, reviewer: field('reviewer'), comment: field('comment'), response: field('response'), location: field('location'), status: item.status ?? 'open' };
  });
  return withLock(`review:${id}`, async () => {
    const root = await registeredRoot(workspaceRoot, id); const metadata = await assertNoSymlinks(root, `reviews/${roundId}/round.json`); const round = await readJson<ReviewRound>(metadata);
    round.items = items; await writeJson(metadata, round);
    const generated = await assertNoSymlinks(root, `reviews/${roundId}/response/responses.tex`, true); await atomicWrite(generated, responses(items));
    return round;
  });
}
